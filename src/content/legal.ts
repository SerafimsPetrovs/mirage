export function getLegalDoc(slug: LegalSlug, locale: Locale): LegalDoc {
  const doc = (locale === "ru" ? ru : en)[slug];
  return {
    title: doc.title,
    intro: fillCompany(doc.intro),
    sections: doc.sections.map((s) => ({ h: s.h, p: s.p.map((p) => fillCompany(p)) })),
  };
}
